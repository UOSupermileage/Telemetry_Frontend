import { apiFetch } from './apiClient'
import { toDisplayValue } from './telemetryUnits'

/**
 * Convert ONE raw API observation to UI units, preserving missing values.
 * Contract: tick ms since boot; speed m/h; current mA; voltage mV;
 * throttle tenths of percent. The raw record is never mutated.
 *
 * @example
 * normalizeTelemetrySample({tick: 1200, speed: 25000, current: 1500,
 *   voltage: 48000, throttle: 100}, 1000)
 * // {elapsed_s: 0.2, speed_kmh: 25, current_a: 1.5,
 * //  voltage_v: 48, power_w: 72, throttle_pct: 10}
 */
export function normalizeTelemetrySample(raw, startTick) {
  const tick = raw?.tick == null ? null : Number(raw.tick)
  const current = toDisplayValue(raw?.current, 'current')
  const voltage = toDisplayValue(raw?.voltage, 'voltage')
  return {
    // Boot-relative time, not a Unix timestamp.
    elapsed_s: Number.isFinite(tick) && Number.isFinite(startTick) ? (tick - startTick) / 1000 : null,
    speed_kmh: toDisplayValue(raw?.speed, 'speed'),
    current_a: current,
    voltage_v: voltage,
    throttle_pct: toDisplayValue(raw?.throttle, 'throttle'),
    power_w: current === null || voltage === null ? null : current * voltage,
  }
}

/**
 * Read-only overview for the explorer. /telemetry/data uses max_points to
 * sample an entire run across its tick range. Statistics generated by the
 * scatter are therefore ONLY descriptive of these returned samples.
 * Full-resolution statistics must be computed separately on the backend.
 *
 * `fetcher` is injectable only to test the adapter without a live server.
 */
export async function getAppRunSamples(runId, { signal, maxPoints = 600, fetcher = apiFetch } = {}) {
  const budget = Number.isFinite(maxPoints) ? Math.max(2, Math.min(10000, Math.floor(maxPoints))) : 600
  const query = new URLSearchParams({
    run_id: String(runId),
    max_points: String(budget),
  })
  for (const field of ['tick', 'speed', 'current', 'voltage', 'throttle']) {
    query.append('fields', field)
  }
  const points = await fetcher(`/telemetry/data?${query}`, { signal })
  if (!Array.isArray(points)) throw new Error('Telemetry API did not return an array')
  const firstTick = points[0]?.tick == null ? null : Number(points[0].tick)
  return points.map((point) => normalizeTelemetrySample(point, firstTick))
}
